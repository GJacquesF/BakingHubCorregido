const CACHE_PREFIX = 'baking-hub-';
const SHELL_CACHE = `${CACHE_PREFIX}shell-v6`;
const PAGE_CACHE = `${CACHE_PREFIX}pages-v5`;
const ASSET_CACHE = `${CACHE_PREFIX}assets-v5`;
const OFFLINE_URL = '/offline.html';
const APP_SHELL = [
  OFFLINE_URL,
  '/manifest.webmanifest',
  '/favicon.svg',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png',
];
const BUILD_ASSETS = /* generated by scripts/generate-sw.mjs */ [];
const MAX_CACHED_PAGES = 40;

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      await cache.addAll(APP_SHELL);
      await Promise.all(
        BUILD_ASSETS.map(async (asset) => {
          try {
            await cache.add(asset);
          } catch (error) {
            console.warn(`No se pudo precargar el recurso opcional ${asset}:`, error);
          }
        }),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && ![SHELL_CACHE, PAGE_CACHE, ASSET_CACHE].includes(key))
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

function isCatalogPage(url) {
  const pathname = url.pathname.replace(/^\/en(?=\/|$)/, '') || '/';
  return pathname === '/' || pathname.startsWith('/categoria/') || pathname.startsWith('/producto/');
}

function normalizePathname(pathname) {
  return pathname.length > 1 ? pathname.replace(/\/+$/, '') : pathname;
}

async function findCachedPage(cache, request) {
  const cached = await cache.match(request);
  if (cached) return cached;

  const requestedUrl = new URL(request.url);
  const requestedPath = normalizePathname(requestedUrl.pathname);
  const matchingRequest = (await cache.keys()).find((cachedRequest) => {
    const cachedUrl = new URL(cachedRequest.url);
    return cachedUrl.origin === requestedUrl.origin &&
      normalizePathname(cachedUrl.pathname) === requestedPath;
  });

  return matchingRequest ? cache.match(matchingRequest) : undefined;
}

function isCacheablePublicPage(response) {
  const cacheControl = response.headers.get('Cache-Control') ?? '';
  return response.ok && response.headers.get('Content-Type')?.includes('text/html') &&
    !/\b(private|no-store)\b/i.test(cacheControl);
}

async function storeVisitedPage(request, response) {
  if (!isCacheablePublicPage(response)) return;

  const cache = await caches.open(PAGE_CACHE);
  await cache.put(request, response.clone());
  const requests = await cache.keys();
  await Promise.all(requests.slice(0, Math.max(0, requests.length - MAX_CACHED_PAGES)).map((oldRequest) => cache.delete(oldRequest)));
}

function isCacheableAsset(request, url) {
  if (url.origin === self.location.origin) {
    return ['script', 'style', 'image', 'font'].includes(request.destination);
  }

  return request.destination === 'image' &&
    url.hostname.endsWith('.supabase.co') &&
    url.pathname.includes('/storage/v1/object/public/');
}

async function cacheFirst(request, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  if (cached) return cached;

  try {
    const response = await fetch(request);
    if (response.ok || response.type === 'opaque') {
      try {
        await cache.put(request, response.clone());
      } catch (error) {
        console.error('No se pudo guardar un recurso en caché:', error);
      }
    }
    return response;
  } catch (error) {
    console.error('No se pudo cargar un recurso sin conexión:', error);
    return new Response('', { status: 503, statusText: 'Recurso no disponible sin conexión' });
  }
}

async function networkFirstPage(request) {
  let response;
  try {
    response = await fetch(request);
  } catch (error) {
    console.info('Sin conexión: intentando cargar la página guardada.', error);
    const pageCache = await caches.open(PAGE_CACHE);
    const cachedPage = isCatalogPage(new URL(request.url)) ? await findCachedPage(pageCache, request) : null;
    if (cachedPage) return cachedPage;
    if (new URL(request.url).pathname === '/') {
      const cachedEnglishHome = await findCachedPage(pageCache, new Request(new URL('/en/', self.location.origin)));
      if (cachedEnglishHome) return cachedEnglishHome;
    }

    return (await caches.match(OFFLINE_URL)) ??
      new Response('Sin conexión y no hay contenido guardado.', {
        status: 503,
        headers: { 'Content-Type': 'text/plain; charset=utf-8' },
      });
  }

  if (isCatalogPage(new URL(request.url))) {
    try {
      await storeVisitedPage(request, response);
    } catch (error) {
      console.error('No se pudo guardar la página del catálogo:', error);
    }
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);

  if (request.method !== 'GET' || url.origin !== self.location.origin && !isCacheableAsset(request, url)) return;

  if (url.origin === self.location.origin && url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate' && url.origin === self.location.origin) {
    event.respondWith(networkFirstPage(request));
    return;
  }

  if (isCacheableAsset(request, url)) {
    event.respondWith(cacheFirst(request, ASSET_CACHE));
  }
});
