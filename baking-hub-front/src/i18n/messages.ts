export type AppLocale = keyof typeof messages;

export function hasEnglishText(spanishText: string): boolean {
  return Object.hasOwn(englishTextBySpanish, spanishText);
}

export function localizedText(
  locale: AppLocale,
  spanishText: string,
  params: Record<string, string | number> = {},
): string {
  const text = locale === 'en'
    ? englishTextBySpanish[spanishText]
    : spanishText;
  if (text === undefined) {
    throw new Error(`Missing English translation for "${spanishText}".`);
  }
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}
