import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(projectDir, 'dist');
const sourcePath = path.join(projectDir, 'public', 'sw.js');
const targetPath = path.join(outputDir, 'sw.js');

async function findBuildAssets(directory, relativeDirectory = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const assets = [];

  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDirectory, entry.name);
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      assets.push(...(await findBuildAssets(absolutePath, relativePath)));
    } else if (/\.(?:css|js|woff2?|ttf|svg|png|jpe?g|webp|avif)$/i.test(entry.name)) {
      assets.push(`/_astro/${relativePath}`);
    }
  }

  return assets;
}

const buildAssets = await findBuildAssets(path.join(outputDir, '_astro'));
const source = await readFile(sourcePath, 'utf8');
const marker = '/* generated by scripts/generate-sw.mjs */ []';
if (!source.includes(marker)) {
  throw new Error(`No se encontró el marcador de precache en ${sourcePath}.`);
}

await writeFile(targetPath, source.replace(marker, JSON.stringify(buildAssets)), 'utf8');
console.log(`Service worker listo: ${buildAssets.length} recursos estáticos en precache.`);
